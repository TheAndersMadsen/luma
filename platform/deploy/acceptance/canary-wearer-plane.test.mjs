test("the mint survives the Secure cookies Center actually sets over loopback http", async (t) => {
  /*
   * THE DEFECT THIS FILE WAS WRITTEN AROUND AND DID NOT CATCH.
   *
   * The first time this gate ever executed against production it failed with
   * "Center's login could not obtain a sealed bearer" — not because anything in
   * the deployment was wrong, but because curl DISCARDS a `Secure` cookie that
   * arrived over an http URL, and the login is loopback http by design. Center
   * sets all four cookies Secure under NODE_ENV=production, so curl's jar came
   * back empty on every possible run, quiesced or not. Observed on the host with
   * curl 8.5.0, against both http://127.0.0.1:14000 and http://localhost:14000:
   * four Set-Cookie headers received, zero cookies stored.
   *
   * The old stub hid it exactly: it honoured --cookie-jar, which real curl
   * would not have. This drives the mint against the real response headers.
   */
  const directory = await workspace(t);
  const secret = await secretFile(directory);
  const stubHeaders = path.join(directory, "stub.headers");
  await writeFile(stubHeaders, loginHeaders({ chunks: 3 }), { mode: 0o600 });
  const output = path.join(directory, "wearer.cookies");
  const result = bash(
    `source "$1"
${stubbedCurl}
WEARER_CANARY_SECRET="$2"
export STUB_HEADERS="$3" STUB_STATUS=200 SPY_ARGV="$4" SPY_BODY="$5"
write_wearer_canary_jar "$6"`,
    [secret, stubHeaders, path.join(directory, "argv.txt"), path.join(directory, "body.json"), output],
  );
  assert.equal(result.status, 0, result.stderr);
  const rows = (await readFile(output, "utf8")).trimEnd().split("\n").slice(1).map((line) => line.split("\t"));
  const loopback = rows.filter((row) => row[0] === "127.0.0.1");
  assert.deepEqual(
    loopback.map((row) => row[5]),
    ["carry_session", "carry_tokens", "carry_tokens.0", "carry_tokens.1", "carry_tokens.2"],
  );
  // The manifest keeps the percent-encoded form Next.js emits, because that is
  // what a browser sends back; decoding it here would rewrite the cookie.
  assert.equal(loopback[1][6], "v1%3A3");
  assert.equal(fs.statSync(output).mode & 0o777, 0o600);
});

test("a login that sets no cookie is refused, and a cleared cookie is not a credential", async (t) => {
  const directory = await workspace(t);

  // 200 with no Set-Cookie at all: the shape a misrouted or cached response
  // takes, and the one that must not be mistaken for the Secure-cookie defect.
  const empty = path.join(directory, "empty.headers");
  await writeFile(empty, loginHeaders({ cookies: false }), { mode: 0o600 });
  const refused = bash(`source "$1"; write_login_cookie_jar "$2" "$3"`, [empty, path.join(directory, "empty.cookies")]);
  assert.notEqual(refused.status, 0);
  assert.match(refused.stderr, /set no cookie at all/);

  // Center clears with Max-Age=0. A jar that stored the clearing cookie would
  // present an emptied session as a complete one.
  const cleared = path.join(directory, "cleared.headers");
  await writeFile(
    cleared,
    "HTTP/1.1 200 OK\r\nset-cookie: carry_session=; Path=/; Max-Age=0; Secure; HttpOnly\r\n" +
      "set-cookie: carry_tokens=v1%3A1; Path=/; Max-Age=43200; Secure; HttpOnly\r\n\r\n",
    { mode: 0o600 },
  );
  const jar = path.join(directory, "cleared.cookies");
  assert.equal(bash(`source "$1"; write_login_cookie_jar "$2" "$3"`, [cleared, jar]).status, 0);
  const names = (await readFile(jar, "utf8")).trimEnd().split("\n").slice(1).map((line) => line.split("\t")[5]);
  assert.deepEqual(names, ["carry_tokens"]);
  const normalized = bash(`source "$1"; normalize_wearer_canary_jar "$2" "$3"`, [jar, path.join(directory, "out.cookies")]);
  assert.notEqual(normalized.status, 0);
  assert.match(normalized.stderr, /set no session cookie/);
});

