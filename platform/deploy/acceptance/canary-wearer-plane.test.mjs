test("the credential is proven least-privilege at runtime, not merely in the runbook", () => {
  /*
   * A gate that assumes its own credential is scoped correctly is a gate that
   * hands an attacker the paired wearer's account the first time somebody
   * provisions it lazily. Both refusals are cheap and both are absolute: the
   * canary identity may not be the paired Pin owner, and it may not be an
   * operator.
   *
   * THE CONDITION IS PINNED WITH THE SENTENCE, NOT INSTEAD OF IT. A `|| fail
   * "…"` line survives every relaxation of the test above it: widening the
   * status check to `403 || 200` — which is exactly what accepting an
   * operator-privileged canary looks like — leaves the message byte-identical
   * and a message-only assertion green. The refusal text is the part a reader
   * greps for; the test above it is the part that decides.
   */
  assert.match(
    canary,
    /^  \[\[ -n "\$wearer_owner_sub" && "\$wearer_subject" != "\$wearer_owner_sub" \]\] \\\n    \|\| fail "the canary wearer credential is the paired Pin owner; provision a dedicated canary identity"$/m,
  );
  // 403 and nothing else. 401 would mean the jar is never read, so the whole
  // block below proves nothing; 200 would mean the operator provisioned an
  // operator, and a canary that can reach /api/admin is a canary whose stolen
  // jar is worth the admin plane.
  assert.match(
    canary,
    /^  \[\[ "\$wearer_admin_status" == 403 \]\] \\\n    \|\| fail "the canary wearer is not a least-privilege wearer: \/api\/admin\/overview answered \$wearer_admin_status \(403 is the only correct answer\)"$/m,
  );
  // `live` has to be earned by the bearer. CARRY_PRINCIPAL is cosmos.ts's
  // identity fallback; a deployment that set it would satisfy every assertion
  // below while proving nothing about the token chain. `exit found?1:0` is the
  // whole check — an awk that always exits 0 makes the `|| fail` unreachable.
  assert.match(
    canary,
    /^    \| awk -F= '\$1=="CARRY_PRINCIPAL" && length\(\$2\)>0 \{found=1\} END\{exit found\?1:0\}' \\\n    \|\| fail "Center injects CARRY_PRINCIPAL, so a live wearer plane would prove nothing about the bearer chain"$/m,
  );
});

test("the assertions are about substance, so a 200 with an empty or error body fails", () => {
  /*
   * Every route in the loop answers 200 whether the read succeeded or collapsed
   * — that is Center's honest-degradation contract and it is correct. Status is
   * therefore not evidence of anything, which is why the previous credential-free
   * gate could pass a deployment where every wearer saw nothing.
   */
  // The status gate that gets the bodies at all. Pinned as the comparison and
  // not as its message, for the reason given in the least-privilege test above:
  // `[[ "$surface_status" != 999 ]]` keeps the sentence and refuses nothing.
  assert.match(
    canary,
    /^    \[\[ "\$surface_status" == 200 \]\] \\\n      \|\| fail "Center wearer surface must answer 200 for a sealed-bearer session: \$route \(\$surface_status\)"$/m,
  );
  assert.match(canary, /^        assert "error" not in payload, f"\{name\} answered 200 with an error body: \{payload\.get\('error'\)\}"$/m);
  assert.match(canary, /^    assert plane\.get\("state"\)=="live", f"the \{half\} wearer plane is not live: \{plane\.get\('detail'\)\}"$/m);
  assert.match(canary, /^assert state\("notes"\)=="live", "the notes REST projection is not live for a sealed-bearer session"$/m);
  assert.match(canary, /^assert state\("memories"\)=="live", "the memories aggregate is not live for a sealed-bearer session"$/m);
  assert.match(canary, /^    assert detail\.get\("state"\)=="live", f"a wearer data part is not live: \{part\} \(\{detail\.get\('degraded'\)\}\)"$/m);
  assert.match(canary, /^assert state\("wifi"\)=="live", "the Wi-Fi pane did not resolve for a sealed-bearer session"$/m);
  // An empty `networks` is the CORRECT live answer — Center cannot open
  // device-sealed envelopes — so the substance is the count, which only a real
  // backend answer produces.
  assert.match(canary, /^assert isinstance\(wifi\.get\("sealedCount"\),int\) and wifi\["sealedCount"\]>=0, \($/m);
});

