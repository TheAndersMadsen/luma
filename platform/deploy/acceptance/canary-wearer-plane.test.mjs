/*
 * A password that is a real one in every respect that matters here: long enough
 * to clear the weak-credential refusal, and containing the shell and JSON
 * metacharacters that a naive interpolation would mangle or, worse, execute.
 * It is a fixture value for a Keycloak user that does not exist; nothing in this
 * repository provisions it and nothing on any host accepts it.
 */
const FIXTURE_PASSWORD = String.raw`fixture-"pw'$(echo no)\backslash|&;<>`;
const FIXTURE_USERNAME = "canary@fixture.invalid";

function bash(script, args = []) {
  return spawnSync("bash", ["-c", script, "fixture", common, ...args], {
    encoding: "utf8",
    maxBuffer: 8 * 1024 * 1024,
  });
}

async function workspace(t) {
  const directory = await mkdtemp(path.join(os.tmpdir(), "revival-canary-wearer-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  return directory;
}

async function secretFile(directory, { username = FIXTURE_USERNAME, password = FIXTURE_PASSWORD, mode = 0o600, body = null } = {}) {
  const file = path.join(directory, "canary-wearer.secret");
  await writeFile(
    file,
    body ?? `REVIVAL_CANARY_WEARER_USERNAME=${username}\nREVIVAL_CANARY_WEARER_PASSWORD=${password}\n`,
    { mode },
  );
  await chmod(file, mode);
  return file;
}

/* The raw jar shape normalize_wearer_canary_jar consumes: session, manifest, chunks. */
function curlJar({ chunks = 2, manifest = null, session = "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiJjYW5hcnktc3ViamVjdCJ9.c2ln" } = {}) {
  const rows = ["# Netscape HTTP Cookie File", "# This file was generated by libcurl!"];
  const push = (name, value) => rows.push(`#HttpOnly_127.0.0.1\tFALSE\t/\tTRUE\t0\t${name}\t${value}`);
  push("carry_session", session);
  if (manifest !== "none") push("carry_tokens", manifest ?? `v1:${chunks}`);
  for (let index = 0; index < chunks; index += 1) push(`carry_tokens.${index}`, `chunk${index}${"A".repeat(40)}`);
  return `${rows.join("\n")}\n`;
}

/*
 * What Center ACTUALLY answers a successful login with, down to the two details
 * that broke the first real run of this gate against production:
 *
 *   * every cookie is `Secure`, because NODE_ENV=production sets it, while the
 *     login is loopback http — curl stores none of them, which is why the mint
 *     reads Set-Cookie itself instead of using --cookie-jar;
 *   * Next.js percent-encodes the value, so the `v1:N` manifest arrives as
 *     `v1%3AN`.
 *
 * The fixture carries both, so a rewrite that reinstates either assumption fails
 * here instead of inside a cutover window.
 */
function loginHeaders({ chunks = 2, manifest = null, session = "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiJjYW5hcnktc3ViamVjdCJ9.c2ln", cookies = true } = {}) {
  const lines = ["HTTP/1.1 200 OK", "content-type: application/json"];
  const push = (name, value) =>
    lines.push(`set-cookie: ${name}=${value}; Path=/; Max-Age=43200; Secure; HttpOnly; SameSite=lax`);
  if (cookies) {
    push("carry_session", session);
    if (manifest !== "none") push("carry_tokens", encodeURIComponent(manifest ?? `v1:${chunks}`));
    for (let index = 0; index < chunks; index += 1) push(`carry_tokens.${index}`, `chunk${index}${"A".repeat(40)}`);
  }
  return `${lines.join("\r\n")}\r\n\r\n`;
}

test("the credential contract accepts exactly one well-formed provisioning", async (t) => {
  const directory = await workspace(t);
  const file = await secretFile(directory);
  const accepted = bash(`source "$1"; assert_wearer_canary_secret "$2"`, [file]);
  assert.equal(accepted.status, 0, accepted.stderr);
  // Nothing about the credential may reach stdout or stderr, not even a length:
  // this function runs inside preflight, whose output is captured into a deploy
  // log an operator pastes into an issue.
  assert.equal(accepted.stdout.trim(), "");
  assert.equal(accepted.stderr.trim(), "");
  assert.ok(!(accepted.stdout + accepted.stderr).includes(FIXTURE_PASSWORD));
});

test("every unsafe provisioning is refused, and the refusal names the property", async (t) => {
  const directory = await workspace(t);

  /*
   * Each case is a real way this gets provisioned wrong. The mode and ownership
   * ones are not ceremony: this file is a live wearer credential sitting in the
   * same directory as center.env, and a 0644 copy of it is readable by every
   * process on the host.
   */
  const cases = [
    ["absent", async () => path.join(directory, "not-provisioned")],
    ["group-readable", async () => secretFile(await sub(directory, "mode"), { mode: 0o640 })],
    ["world-readable", async () => secretFile(await sub(directory, "world"), { mode: 0o644 })],
    ["a symlink", async () => {
      const nested = await sub(directory, "link");
      const real = await secretFile(nested);
      const link = path.join(nested, "linked.secret");
      await symlink(real, link);
      return link;
    }],
    ["an extra key", async () => secretFile(await sub(directory, "extra"), {
      body: `REVIVAL_CANARY_WEARER_USERNAME=${FIXTURE_USERNAME}\nREVIVAL_CANARY_WEARER_PASSWORD=${FIXTURE_PASSWORD}\nCARRY_ADMIN_TOKEN=something-else\n`,
    })],
    ["a missing key", async () => secretFile(await sub(directory, "missing"), {
      body: `REVIVAL_CANARY_WEARER_USERNAME=${FIXTURE_USERNAME}\n`,
    })],
    ["an empty value", async () => secretFile(await sub(directory, "empty"), { password: "" })],
    ["a placeholder password", async () => secretFile(await sub(directory, "short"), { password: "changeme" })],
    ["the username reused as the password", async () => secretFile(await sub(directory, "same"), {
      username: "reused-credential-value",
      password: "reused-credential-value",
    })],
    ["a control character", async () => secretFile(await sub(directory, "control"), {
      body: `REVIVAL_CANARY_WEARER_USERNAME=${FIXTURE_USERNAME}\nREVIVAL_CANARY_WEARER_PASSWORD=with\ttab-and-more-length\n`,
    })],
    ["a line that is not KEY=VALUE", async () => secretFile(await sub(directory, "garbage"), {
      body: `REVIVAL_CANARY_WEARER_USERNAME=${FIXTURE_USERNAME}\nREVIVAL_CANARY_WEARER_PASSWORD=${FIXTURE_PASSWORD}\nnot an assignment\n`,
    })],
  ];

  for (const [label, build] of cases) {
    const file = await build();
    const result = bash(`source "$1"; assert_wearer_canary_secret "$2"`, [file]);
    assert.notEqual(result.status, 0, `an unsafe credential was accepted: ${label}`);
    assert.ok(result.stderr.trim().length > 0, `the refusal for ${label} said nothing`);
    assert.ok(
      !(result.stdout + result.stderr).includes(FIXTURE_PASSWORD),
      `the refusal for ${label} echoed the credential`,
    );
  }

  async function sub(base, name) {
    const nested = path.join(base, name);
    await mkdir(nested, { recursive: true, mode: 0o700 });
    await chmod(nested, 0o700);
    return nested;
  }
});

