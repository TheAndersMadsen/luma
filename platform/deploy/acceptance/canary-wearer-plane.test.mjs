/*
 * The end-to-end mint, against a stubbed Center.
 *
 * `curl` is shadowed by a shell function after common.sh is sourced, so the real
 * write_wearer_canary_jar runs: it validates the secret, writes the body,
 * "posts" it, and normalizes what comes back. The stub records the arguments it
 * was handed, which is how the argv claim in the comment above that function is
 * checked rather than believed.
 */
const stubbedCurl = String.raw`
curl() {
  local previous="" argument headers="" body=""
  printf '%s\n' "$@" >"$SPY_ARGV"
  for argument in "$@"; do
    # -D, not --cookie-jar: curl's cookie engine discards a Secure cookie that
    # arrived over http, so the mint reads the response headers directly. A stub
    # that answered --cookie-jar would be a more permissive curl than the real
    # one, which is exactly the gap that let this ship broken.
    if [[ "$previous" == -D ]]; then headers="$argument"; fi
    if [[ "$previous" == --cookie-jar ]]; then echo 'the mint asked curl to store cookies it will not store' >&2; return 1; fi
    if [[ "$previous" == --data ]]; then body="$(printf '%s' "$argument" | sed 's/^@//')"; fi
    previous="$argument"
  done
  if [[ -n "$body" ]]; then cp -- "$body" "$SPY_BODY"; fi
  if [[ -n "$headers" ]]; then cp -- "$STUB_HEADERS" "$headers"; fi
  printf '%s' "$STUB_STATUS"
}
`;

/*
 * A seam into the mint's private workspace.
 *
 * write_wearer_canary_jar does its work in a `mktemp -d` it removes on the way
 * out, so nothing the caller can name survives to be inspected — which is
 * correct, and which is also why the "the body file is deleted" claim has to be
 * observed from INSIDE. normalize_wearer_canary_jar is the first thing to run
 * after the request, and its first argument lives in that workspace, so
 * wrapping it lists the directory at exactly the instant the credential body
 * must already be gone. The real function still runs, so nothing else about the
 * case is stubbed out.
 */
const spiedNormalize = String.raw`
eval "spied_original_normalize() $(declare -f normalize_wearer_canary_jar | tail -n +2)"
normalize_wearer_canary_jar() {
  ls -A -- "$(dirname -- "$1")" >"$SPY_WORK"
  spied_original_normalize "$@"
}
`;

test("a successful sign-in yields a jar, and the credential never reaches argv", async (t) => {
  const directory = await workspace(t);
  const secret = await secretFile(directory);
  const stubHeaders = path.join(directory, "stub.headers");
  await writeFile(stubHeaders, loginHeaders({ chunks: 2 }), { mode: 0o600 });
  const output = path.join(directory, "wearer.cookies");
  const spyArgv = path.join(directory, "argv.txt");
  const spyBody = path.join(directory, "body.json");
  const spyWork = path.join(directory, "workspace.txt");

  const result = bash(
    `source "$1"
${stubbedCurl}
${spiedNormalize}
WEARER_CANARY_SECRET="$2"
export STUB_HEADERS="$3" STUB_STATUS=200 SPY_ARGV="$4" SPY_BODY="$5" SPY_WORK="$7"
write_wearer_canary_jar "$6"`,
    [secret, stubHeaders, spyArgv, spyBody, output, spyWork],
  );
  assert.equal(result.status, 0, result.stderr);
  assert.equal(fs.statSync(output).mode & 0o777, 0o600);

  const argv = await readFile(spyArgv, "utf8");
  // The whole point of `--data @path`: the request carries the credential and
  // the process table does not. A future rewrite that builds an inline body
  // fails here.
  assert.ok(!argv.includes(FIXTURE_PASSWORD), "the credential appeared in curl's arguments");
  assert.ok(!argv.includes(FIXTURE_USERNAME), "the canary identity appeared in curl's arguments");
  assert.match(argv, /^--data$/m);
  // Loopback only. A credential that traverses the public edge is a credential
  // in somebody's access log, and the quiesced window has no public edge at all.
  assert.match(argv, /^http:\/\/127\.0\.0\.1:14000\/api\/auth\/login$/m);

  const body = JSON.parse(await readFile(spyBody, "utf8"));
  assert.equal(body.password, FIXTURE_PASSWORD);
  assert.ok(!(result.stdout + result.stderr).includes(FIXTURE_PASSWORD));

  // The body file is removed as soon as the request is made, rather than living
  // for the length of the canary run.
  //
  // Observed inside write_wearer_canary_jar's own `mktemp -d` workspace, which
  // is where the body actually is. Looking for it beside the fixture directory
  // asserted nothing at all: that path is never written, so the check passed
  // whether or not the `rm -f` existed.
  const workspaceEntries = (await readFile(spyWork, "utf8")).split("\n").filter(Boolean);
  assert.ok(workspaceEntries.includes("raw.cookies"), "the mint's workspace was not observed");
  assert.ok(
    !workspaceEntries.includes("login.json"),
    "the credential body outlived the request that carried it",
  );
});

