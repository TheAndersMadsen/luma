/*
 * THE CANARY WEARER CREDENTIAL, AND THE COVERAGE IT BUYS.
 *
 * Two 100%-wearer-facing outages passed every deploy gate. Both had the same
 * shape: Center answered every request with 200 and an honest `degraded` body
 * while every wearer saw an empty dashboard, and nothing in the canary held a
 * credential capable of telling the difference. The canary said so — it printed
 * "a 100%-degraded wearer plane would pass this canary" — and shipped anyway,
 * because a warning is not a gate.
 *
 * What closes it is one sealed Keycloak bearer for a DEDICATED canary identity,
 * obtained through Center's own POST /api/auth/login, which is the only path in
 * this system that produces the `carry_tokens` cookie set. These tests cover the
 * two halves that can be tested without a VPS:
 *
 *   1. THE CREDENTIAL CONTRACT, executed. assert_wearer_canary_secret,
 *      write_wearer_canary_login_body, normalize_wearer_canary_jar,
 *      wearer_canary_jar_subject and write_wearer_canary_jar are real functions
 *      in common.sh with no VPS dependency beyond `curl`, so they are driven
 *      here against fixtures and a stubbed Center, including every refusal.
 *
 *   2. THE SHAPE OF THE GATE, pinned. Whether the coverage runs by DEFAULT,
 *      whether the escape hatch stays out of the automation, and whether the
 *      credential can leak into an evidence file — none of which a fixture can
 *      demonstrate, all of which are how the previous version failed.
 *
 * FILE RULE, inherited from deploy-gates.test.mjs and for the same reason: every
 * positive source pin is line-anchored (`^…$` with the `m` flag). These scripts
 * explain themselves in prose, so a substring pin over this subject matter is
 * satisfied by the comment describing the check as readily as by the check.
 */

