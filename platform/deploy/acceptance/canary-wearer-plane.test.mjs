test("nothing that survives the run can carry the credential", () => {
  /*
   * The credential must not widen what reading a log, an evidence file or a
   * deployment record is worth. The secret lives in $PRIVATE_DIR and is
   * deliberately absent from the protected-configuration inventory, because
   * fingerprinting it there would make a routine credential rotation trip the
   * config-drift gate and deadlock a deploy.
   */
  assert.match(commonSource, /^WEARER_CANARY_SECRET="\$PRIVATE_DIR\/canary-wearer.secret"$/m);
  const inventory = commonSource.slice(at(commonSource, "edge.envoy\t$PRIVATE_DIR/edge/envoy.yaml"));
  assert.doesNotMatch(inventory.slice(0, 4000), /canary-wearer/);
  // It is not an env-file key either: those are interpolated into Compose and
  // land in container environments, where a workload could read it.
  for (const source of [commonSource, canary, deploy, preflight]) {
    assert.doesNotMatch(source, /REVIVAL_CANARY_WEARER_PASSWORD=/);
  }
  // The jar lives in the canary's own mktemp workspace, which the EXIT trap
  // removes, and is deleted explicitly as soon as the assertions are done.
  assert.match(canary, /^  wearer_jar="\$work\/wearer.cookies"$/m);
  assert.match(
    canary,
    /^  rm -f -- "\$work"\/sealed-\*\.json "\$work"\/sealed-\*\.headers "\$wearer_cookie_header" "\$wearer_jar"$/m,
  );
});

test("the JSON result cannot be read as wearer coverage it does not have", () => {
  // A machine reader that treats ok:true as "wearers are fine" is the original
  // failure one level up. The field says which of the two it is, in words.
  assert.match(canary, /^    "wearerPlane":"sealed-bearer" if sys\.argv\[3\]=="1" else "unproven",$/m);
  // And argv[3] has to be the flag the assertions set. Pinning the ternary
  // alone leaves `python3 - "$release_id" "$crud" 1` green — a literal that
  // makes every run claim sealed-bearer coverage, which is the same lie this
  // field exists to prevent, told through the one input the field reads.
  assert.match(
    canary,
    /^  python3 - "\$release_id" "\$crud" "\$wearer_plane_proven" <<'PY'$/m,
    "the JSON verdict must be fed the flag the wearer-plane assertions set, not a literal",
  );
});
